// «Crea il tuo portafoglio»: modello pronto + uno strumento scritto a mano → prezzi di mercato → laboratorio.
import { spawn } from "node:child_process";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const puppeteer = require("puppeteer-core");
const [,, OUT] = process.argv, PORT = 5171, wait = ms => new Promise(r => setTimeout(r, ms));
const srv = spawn(process.execPath, [import.meta.dirname + "/serve.mjs"], { env: { ...process.env, PORT: String(PORT), REAL_PRICES: "1" }, stdio: "ignore" });
await wait(1500);
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true, args: ["--no-sandbox"] });
const p = await b.newPage(); await p.setViewport({ width: 1440, height: 900 }); const errs = [];
p.on("pageerror", e => errs.push(e.message));
let pass = 0, fail = 0;const t = (n, ok, i = "") => { ok ? pass++ : fail++; console.log(`  ${ok ? "ok     " : "FALLITO"} ${n}${!ok && i ? " · " + i : ""}`); };
await p.goto(`http://localhost:${PORT}/`, { waitUntil: "networkidle2" }); await wait(5000);
await p.click("#builderBtn"); await wait(700);
t("il pannello si apre", await p.evaluate(() => document.getElementById("builder").classList.contains("open")));
await p.evaluate(() => [...document.querySelectorAll("[data-bdp]")].find(x => /satelliti/i.test(x.textContent)).click()); await wait(300);
t("modello «Core e satelliti»: 4 strumenti, totale 100%", await p.evaluate(() => document.querySelectorAll("#bdRows .bd-row").length === 4 && /100%/.test(document.getElementById("bdSum").textContent)));
await p.click("#bdAdd"); await wait(200);
await p.evaluate(() => { const ins = document.querySelectorAll("#bdRows input[list]"), last = ins[ins.length - 1]; last.value = "IE00B4ND3602"; last.dispatchEvent(new Event("change", { bubbles: true })); });
await wait(200);
await p.evaluate(() => { const ws = document.querySelectorAll("#bdRows input[data-bdw]"), last = ws[ws.length - 1]; last.value = "10"; last.dispatchEvent(new Event("change", { bubbles: true })); });
await wait(300);
t("ISIN scritto a mano riconosciuto (oro fisico)", await p.evaluate(() => /Physical Gold/.test(document.getElementById("bdRows").innerText)));
t("totale 110%: avviso che si riporta a 100%", await p.evaluate(() => /110%[\s\S]*100%/.test(document.getElementById("bdSum").textContent)));
await p.screenshot({ path: `${OUT}/bd-1.jpg`, type: "jpeg", quality: 70 });
await p.click("#bdGo");
const inLab = await p.waitForFunction(() => document.body.dataset.scene === "lab" && !document.getElementById("lab").hidden, { timeout: 150000 }).then(() => true).catch(() => false);
const st = await p.evaluate(() => window.__pos.state());
t("dritto al laboratorio dopo i prezzi di mercato", inLab, JSON.stringify(st.checks));
t("5 strumenti con prezzi di mercato", st.assets.length === 5, st.assets.join(","));
t("pesi del portafoglio = quelli scelti (riproporzionati)", await p.evaluate(() => { const pf = window.__pos.pf(); const tot = pf.positions.reduce((a, x) => a + x.valore, 0); const sw = pf.positions.find(x => x.ticker === "SWDA"); return sw && Math.abs(sw.valore / tot - 70 / 110) < .001; }));
t("nessuna lettura con l'IA", await p.evaluate(() => !window.__pos.state().recipe || window.__pos.state().recipe.status !== "loading"));
await wait(2500); await p.screenshot({ path: `${OUT}/bd-2.jpg`, type: "jpeg", quality: 70 });
t("nessun errore JavaScript", !errs.length, errs.join(" | "));
console.log(`\n${pass} superati, ${fail} falliti`);
await b.close(); srv.kill(); process.exit(fail ? 1 : 0);
