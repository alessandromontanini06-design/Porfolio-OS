// Impostazioni (rotellina) e modalità chiara/scura: scelta, memoria dopo la ricarica, «Automatico» che segue il sistema,
// colori davvero scuri, pannello sopra le barre e dentro lo schermo del telefono, privacy che segue la scelta.
import { spawn } from "node:child_process"; import { createRequire } from "node:module";
const require = createRequire(import.meta.url); const puppeteer = require("puppeteer-core");
const OUT = process.argv[2] || "files/shots", wait = ms => new Promise(r => setTimeout(r, ms));
const SITE = process.env.SITE || "http://localhost:5304";
const srv = process.env.SITE ? null : spawn(process.execPath, [import.meta.dirname + "/serve.mjs"], { env: { ...process.env, PORT: "5304" }, stdio: "ignore" });
await wait(1500);
let pass = 0, fail = 0; const t = (n, ok, i = "") => { ok ? pass++ : fail++; console.log(`  ${ok ? "ok     " : "FALLITO"} ${n}${!ok && i ? " · " + i : ""}`); };
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const p = await b.newPage(); const errs = []; p.on("pageerror", e => errs.push(e.message));
await p.setViewport({ width: 1300, height: 800 }); await p.emulateMediaFeatures([{ name: "prefers-color-scheme", value: "light" }]);
await p.goto(SITE + "/?home", { waitUntil: "networkidle2" }); await wait(1500);
const th = () => p.evaluate(() => document.documentElement.dataset.theme);
const bg = () => p.evaluate(() => getComputedStyle(document.body).backgroundColor);
t("si apre chiaro se il sistema è chiaro", await th() === "light");
t("c'è la rotellina delle impostazioni", !!await p.$("#setBtn"));
await p.click("#setBtn"); await wait(400);
t("il pannello si apre", await p.evaluate(() => !document.getElementById("setPop").hidden));
t("«Automatico» è la scelta iniziale", await p.evaluate(() => document.querySelector('[data-tema="auto"]').getAttribute("aria-checked") === "true"));
const top = await p.evaluate(() => { const r = document.querySelector("#setPop .set-h").getBoundingClientRect(); const e = document.elementFromPoint(r.left + 5, r.top + r.height / 2); return !!(e && e.closest("#setPop")); });
t("il pannello sta sopra le barre (il titolo si vede)", top);
await p.click('[data-tema="scuro"]'); await wait(400);
t("«Scuro» mette il sito scuro", await th() === "dark");
const dark = await bg(); t(`lo sfondo è scuro (${dark})`, /rgb\(1[0-9], 1[0-9], 1[0-9]\)|rgb\([0-9], [0-9], [0-9]\)/.test(dark));
t("la scelta resta nel browser", await p.evaluate(() => localStorage.getItem("pos-tema-v1")) === "scuro");
await p.reload({ waitUntil: "networkidle2" }); await wait(800);
t("dopo la ricarica resta scuro", await th() === "dark");
await p.click("#setBtn"); await wait(300); await p.click('[data-tema="chiaro"]'); await wait(300);
t("«Chiaro» torna chiaro", await th() === "light");
await p.emulateMediaFeatures([{ name: "prefers-color-scheme", value: "dark" }]); await wait(300);
t("con «Chiaro» il sistema scuro non cambia nulla", await th() === "light");
await p.click('[data-tema="auto"]'); await wait(300);
t("«Automatico» con il sistema scuro va in scuro", await th() === "dark");
await p.emulateMediaFeatures([{ name: "prefers-color-scheme", value: "light" }]); await wait(300);
t("e segue il sistema quando cambia", await th() === "light");
t("con «Automatico» non resta nulla salvato", await p.evaluate(() => localStorage.getItem("pos-tema-v1")) === null);
await p.keyboard.press("Escape"); await wait(200);
t("Esc chiude il pannello", await p.evaluate(() => document.getElementById("setPop").hidden));
await p.click("#setBtn"); await wait(300); await p.click("#mnuBtn"); await wait(300);
t("aprendo il menu il pannello si chiude", await p.evaluate(() => document.getElementById("setPop").hidden && !document.getElementById("mnuPop").hidden));
await p.click("#mnuBtn"); await wait(200);
await p.emulateMediaFeatures([{ name: "prefers-color-scheme", value: "dark" }]);
await p.setViewport({ width: 390, height: 844 }); await p.reload({ waitUntil: "networkidle2" }); await wait(1200);
await p.click("#setBtn"); await wait(400);
const box = await p.evaluate(() => { const r = document.getElementById("setPop").getBoundingClientRect(); return { l: r.left, r: r.right }; });
t(`sul telefono il pannello sta nello schermo (${Math.round(box.l)}–${Math.round(box.r)} px)`, box.l >= 0 && box.r <= 390);
await p.screenshot({ path: OUT + "/tema-telefono-scuro.jpg", type: "jpeg", quality: 60 });
await p.goto(SITE + "/privacy.html", { waitUntil: "networkidle2" }); await wait(300);
t("anche la privacy segue il tema", await th() === "dark" && /rgb\(1[01], 1[01], 1[0]\)|rgb\(11, 11, 10\)/.test(await bg()), await bg());
t("nessun errore JavaScript", !errs.length, errs.join(" | "));
console.log(`\n${pass} superati, ${fail} falliti`);
await b.close(); if (srv) srv.kill(); process.exit(fail ? 1 : 0);
